#!/usr/bin/env python3
"""vec_cortana.py — the Cortana orb as layered VEC2 (SVF) assets.

The orb is the app's identity: a thick blue ring with a small gap at the
lower right (the "loading" opening) over a pale halo, plus the wider-gap
"thinking" variant used while a query is in flight. Authored with the
same VEC2 command builder as files/tools/vec_icons.py and byte-validated
against payload/phone/svf.c's scan() before the header is emitted.
"""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / '..' / 'app' / 'cortana_vec.h'


class Vec:
    def __init__(self, vw=32, vh=32):
        self.b = bytearray(b'VEC2' + b'\x60' + struct.pack('>hh', vw, vh))

    def style(self, fill=0xffff, stroke=0xffff):
        self.b += b'\x01' + struct.pack('>HH', fill, stroke)
        return self

    def arc(self, cx, cy, r, start, count, width=2):
        self.b += b'\x22' + struct.pack('>hhhBBB', cx, cy, r, start, count, width)
        return self

    def circle(self, x, y, r):
        self.b += b'\x20' + struct.pack('>hhh', x, y, r)
        return self

    def end(self):
        return bytes(self.b + b'\0')


def rgb(r, g, b):
    return (r >> 3) << 10 | (g >> 3) << 5 | (b >> 3)


HALO = rgb(0xC5, 0xD4, 0xFA)    # pale periwinkle halo
RING = rgb(0x4A, 0x71, 0xFF)    # orb blue (measured from the reference)
RING_D = rgb(0x2F, 0x53, 0xD9)  # shade on the ring's inner edge
WHITE = rgb(0xFF, 0xFF, 0xFF)


def ring_home():
    """Home orb: halo disc + thick ring with the small lower-right gap."""
    v = Vec()
    v.style(WHITE).circle(16, 16, 14)          # white field inside the halo
    v.style(0xffff, HALO).arc(16, 16, 13, 0, 32, 2)   # pale halo ring
    v.style(0xffff, RING).arc(16, 16, 10, 5, 30, 4)   # main ring, small gap
    return v.end()


def ring_think():
    """Thinking orb: same geometry, a wider opening + brighter halo."""
    v = Vec()
    v.style(WHITE).circle(16, 16, 14)
    v.style(0xffff, HALO).arc(16, 16, 13, 0, 32, 3)
    v.style(0xffff, RING).arc(16, 16, 10, 18, 25, 4)  # rotated, larger gap
    return v.end()


def validate(data):
    """Byte-exact svf.c scan() port (same as files/tools/vec_icons.py)."""
    b, n = data, len(data)
    if not b or n < 5 or n > 4096 or b[:3] != b'VEC' or b[3] not in (ord('1'), ord('2')):
        return 'magic/size'
    p, commands = 4, 0
    while p < n and commands <= 512:
        op = b[p]
        p += 1
        commands += 1
        if op == 0:
            return None if p == n else 'trailing bytes'
        if op in (1, 0x60):
            need = 4
        elif op in (0x10, 0x21, 0x30):
            need = 8
        elif op in (0x11, 0x22, 0x31):
            need = 9
        elif op == 0x20:
            need = 6
        elif op == 0x40:
            if p >= n or b[p] < 3:
                return 'poly count'
            need = 1 + 4 * b[p]
        elif op == 0x55:
            if p >= n:
                return 'skip'
            need = 1 + b[p]
        elif op == 0x50:
            if n - p < 5:
                return 'text'
            need = 5 + b[p + 4]
        else:
            return f'op {op:#x}'
        if need > n - p:
            return f'op {op:#x} truncated'
        if op in (0x22, 0x31) and (b[p + 8] == 0 or b[p + 8] > 8):
            return 'width'
        if op == 0x22 and (b[p + 6] >= 32 or b[p + 7] > 32):
            return 'arc range'
        p += need
    return 'no end'


def main():
    icons = [('ring_home', ring_home), ('ring_think', ring_think)]
    lines = [
        '/* cortana_vec.h — generated by cortana/tools/vec_cortana.py.',
        ' * The Cortana orb (home + thinking) as layered VEC2 streams for',
        ' * the shared payload/phone/svf.c engine. DO NOT EDIT BY HAND. */',
        '#ifndef CORTANA_VEC_H',
        '#define CORTANA_VEC_H',
        '',
    ]
    for i, (name, fn) in enumerate(icons):
        data = fn()
        err = validate(data)
        if err:
            print(f'{name}: INVALID ({err})', file=sys.stderr)
            return 1
        lines.append(f'#define CV_{name.upper()} {i}')
        lines.append(f'static const unsigned char cv{i}[] = {{'
                     + ','.join(map(str, data)) + '};')
    lines.append('typedef struct { const unsigned char *data; unsigned length; } CortVec;')
    lines.append('static const CortVec cort_vec[] = {'
                 + ','.join('{cv%d,sizeof(cv%d)}' % (i, i) for i in range(len(icons)))
                 + '};')
    lines.append('#endif')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'wrote {OUT} ({len(icons)} orb variants)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
