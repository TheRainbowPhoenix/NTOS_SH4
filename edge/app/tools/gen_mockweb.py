#!/usr/bin/env python3
"""gen_mockweb.py — emit mockweb.h with embedded NUL-terminated page sources.

The router in edge_app.c serves these as if the network stack existed.
Arrays use INTEGER initializers (not string literals) so the bytes are the
actual page text. Sources live in /home/z/my-project/mdtest (acid1.html,
wiki_cp300.md) and the ClasspadDev wiki FAQ (trimmed).
"""
import subprocess
import sys

ACID1 = '/home/z/my-project/mdtest/acid1.html'
WIKI = '/home/z/my-project/mdtest/wiki_cp300.md'
FAQ = '/home/z/my-project/refs-md/wiki-main/src/content/docs/faq.mdx'
OUT = 'mockweb.h'
FAQ_CAP = 9000


def c_array(name, text):
    vals = [str(10 if ch == '\n' else ord(ch)) for ch in text if ch != '\r']
    vals.append('0')
    lines = []
    line = ''
    for v in vals:
        if len(line) + len(v) + 1 > 100:
            lines.append('    ' + line)  # keep trailing comma
            line = ''
        line += v + ','
    lines.append('    ' + line[:-1])  # final value without comma
    return f'static const char {name}[] = {{\n' + '\n'.join(lines) + '\n};'


def main():
    acid1 = open(ACID1).read()
    wiki = open(WIKI).read()
    faq = open(FAQ).read()[:FAQ_CAP]
    hdr = '''/* mockweb.h — the POC's "online" content, served by the URL router as if
 * the network stack existed: the CSS1 ACID1 test page, a Wikipedia article
 * and a wiki FAQ. Embedded NUL-terminated sources keep the device offline.
 * Generated by tools/gen_mockweb.py — do not edit by hand. */
#ifndef MOCKWEB_H
#define MOCKWEB_H

'''
    hdr += c_array('MW_ACID1', acid1) + '\n\n'
    hdr += c_array('MW_WIKI_CP300', wiki) + '\n\n'
    hdr += c_array('MW_CWIKI_FAQ', faq) + '\n\n'
    hdr += '#endif /* MOCKWEB_H */\n'
    open(OUT, 'w').write(hdr)

    # self-check: compile + run a probe that memcmps the arrays
    probe = r'''
#include "mockweb.h"
#include <string.h>
#include <stdio.h>
int main(void) {
    if (MW_ACID1[0] != '<' || MW_ACID1[1] != '!') return 1;
    if (strncmp(MW_WIKI_CP300, "# Casio ClassPad 300", 20) != 0) return 2;
    if (MW_CWIKI_FAQ[0] != '-' || MW_CWIKI_FAQ[1] != '-') return 3;
    printf("ok %zu %zu %zu\n", strlen(MW_ACID1), strlen(MW_WIKI_CP300),
           strlen(MW_CWIKI_FAQ));
    return 0;
}
'''
    open('/tmp/mwprobe.c', 'w').write(probe)
    r = subprocess.run(['gcc', '-I', '.', '-o', '/tmp/mwprobe', '/tmp/mwprobe.c'],
                       capture_output=True, text=True)
    if r.returncode:
        print('probe compile FAILED:', r.stderr[:400])
        return 1
    r2 = subprocess.run(['/tmp/mwprobe'], capture_output=True, text=True)
    print('probe:', r2.stdout.strip(), 'exit', r2.returncode)
    return r2.returncode


if __name__ == '__main__':
    sys.exit(main())
