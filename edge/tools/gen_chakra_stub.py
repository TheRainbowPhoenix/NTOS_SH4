#!/usr/bin/env python3
"""gen_chakra_stub.py — generate the pure-stub chakra.dll source.

The NTOS Edge POC runs without a JS engine: the device profile (100 MHz SH4,
4 MB RAM, no FPU) cannot afford ChakraCore, and the UI is the POC target.
chakra.dll keeps the *API shape* of the real 5.8 MB x86 DLL (160 exports,
see edge/analysis/pe_scan/Chakra.dll.txt) so that EdgeContent-style imports
resolve; everything returns E_NOTIMPL except the handle plumbing needed by
the smoke test.

Regenerate:  python3 tools/gen_chakra_stub.py > app/chakra_stub.c
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCAN = os.path.join(HERE, os.pardir, "analysis", "pe_scan", "Chakra.dll.txt")

# exports with hand-written bodies (real signatures); everything else is
# generated as `int name(void) -> E_NOTIMPL` (ABI-safe: no float args in
# the whole Chakra C API).
SPECIAL = {
    "JsCreateRuntime",
    "JsDisposeRuntime",
    "JsCreateContext",
    "JsSetCurrentContext",
    "JsGetCurrentContext",
    "JsGetValueType",
    "JsRunScript",
}

HEADER = """\
/* chakra_stub.c — PURE-STUB Chakra API for NTOS (generated, do not edit).
 *
 * Generated by edge/tools/gen_chakra_stub.py from the real chakra.dll
 * export table (160 symbols, 32-bit x86, 5.8 MB; see analysis/pe_scan).
 * Every export exists so Wine-style import resolution succeeds; the
 * engine itself is absent by design: this profile (100 MHz SH4, 4 MB RAM,
 * no FPU) runs the UI POC, not JS. The handful of handle APIs return
 * singleton "null engine" handles so lifecycle code paths stay well-formed.
 *
 * The mquickjs-backed behavioural variant (host experiments only) lives in
 * chakra_mqjs.c and builds as chakra-full.dll when engine sources exist;
 * see edge/app/Makefile.
 */
#include "nt_app.h"

#define E_NOTIMPL_ 0x80004001u
#define E_INVALIDARG_ 0x80070057u

/* ---- imports ---- */
NT_IMPORT(void, coredll_puts, (const char *))
NT_DEFINE(coredll_puts)

static char rt_obj, ctx_obj; /* singleton handle identities */

__attribute__((dllexport)) int JsCreateRuntime(unsigned attrs, void *svc, void **rt)
{
    (void)attrs; (void)svc;
    if (!rt)
        return E_INVALIDARG_;
    *rt = &rt_obj;
    return 0;
}

__attribute__((dllexport)) int JsDisposeRuntime(void *rt)
{
    return rt == &rt_obj ? 0 : E_INVALIDARG_;
}

__attribute__((dllexport)) int JsCreateContext(void *rt, void **ctx)
{
    if (rt != &rt_obj || !ctx)
        return E_INVALIDARG_;
    *ctx = &ctx_obj;
    return 0;
}

__attribute__((dllexport)) int JsSetCurrentContext(void *ctx)
{
    return (ctx == &ctx_obj || !ctx) ? 0 : E_INVALIDARG_;
}

__attribute__((dllexport)) int JsGetCurrentContext(void **ctx)
{
    if (!ctx)
        return E_INVALIDARG_;
    *ctx = &ctx_obj;
    return 0;
}

__attribute__((dllexport)) int JsGetValueType(void *v, int *type)
{
    (void)v;
    if (!type)
        return E_INVALIDARG_;
    *type = 0; /* JsUndefined: no engine, nothing was ever produced */
    return 0;
}

/* real signature (4 args) so the smoke test stays honest */
__attribute__((dllexport)) int JsRunScript(const W16 *script, unsigned ctx,
                                           const W16 *url, void **result)
{
    (void)script; (void)ctx; (void)url; (void)result;
    return E_NOTIMPL_; /* no engine on this device profile */
}

/* e2e: API shape check used by the NTOS_SH4_linux run (see Makefile test) */
__attribute__((dllexport)) int ChakraSmokeTest(void)
{
    void *rt, *ctx;
    int rc, type;
    if ((rc = JsCreateRuntime(0, 0, &rt)) != 0)
        return rc;
    if ((rc = JsCreateContext(rt, &ctx)) != 0)
        return rc;
    if ((rc = JsSetCurrentContext(ctx)) != 0)
        return rc;
    if ((rc = JsGetCurrentContext(&ctx)) != 0 || ctx != &ctx_obj)
        return 0x8000FFFFu;
    if ((rc = JsGetValueType(0, &type)) != 0 || type != 0)
        return 0x8000FFFFu;
    if (JsRunScript(0, 0, 0, 0) != E_NOTIMPL_) /* no engine: must fail cleanly */
        return 0x8000FFFFu;
    NT_CALL(coredll_puts, ("chakra_stub: pure-stub API shape OK\\n"));
    return 0;
}
"""


def main():
    names = []
    with open(SCAN, "r", errors="replace") as f:
        in_exports = False
        for line in f:
            if line.startswith("--- EXPORTS ---"):
                in_exports = True
                continue
            if in_exports:
                m = re.match(r"\s+\d+\s+(\w+)\s*$", line)
                if m:
                    names.append(m.group(1))
    if not names:
        print("no exports parsed from", SCAN, file=sys.stderr)
        return 1

    out = [HEADER]
    out.append("\n/* %d generated empty exports */\n" % len(names))
    for n in names:
        if n in SPECIAL:
            continue
        out.append(
            "__attribute__((dllexport)) int %s(void) { return E_NOTIMPL_; }\n" % n
        )
    out.append(
        """
int DllMainCRTStartup_impl(void *h, U32 r, void *r2);
__asm__(".globl _DllMainCRTStartup\\n_DllMainCRTStartup = DllMainCRTStartup_impl\\n");
int DllMainCRTStartup_impl(void *h, U32 r, void *r2)
{
    (void)h; (void)r; (void)r2;
    return 1;
}
"""
    )
    sys.stdout.write("".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
