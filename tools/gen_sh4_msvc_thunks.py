#!/usr/bin/env python3
"""Emit signature-specific SH4 BE MSVC<->GCC *integer-word-only* PE thunks.

Measured shcl 12.00.8281.0 SH4 C ABI:
  words 0..3 => r4..r7, words 4.. => callee entry SP+16..
Native NTOS GCC SH ABI:
  words 0..3 => r4..r7, words 4.. => callee entry SP+0..
All values are uint32_t or pointers. No structs, u64, variadics or FP.
Input is an explicit signature manifest, not guessed from C declarations.
"""
import argparse
from pathlib import Path

# Restrict this first experiment to signatures validated by the fixture.
SPECS = (("abi_msvc5", 5, "ntos_msvc_native5"),
         ("abi_msvc8", 8, "ntos_msvc_native8"))


def generate(role):
    out = [
        "! Generated by tools/gen_sh4_msvc_thunks.py. DO NOT EDIT.",
        "! MSVC SH4 ABI: r4-r7, fifth at entry SP+16, 16-byte home.",
        "! Native GCC SH ABI: r4-r7, fifth at entry SP+0.",
        "! Scalar/pointer U32 arguments and U32 return ONLY.",
        "    .section .text",
        "    .align 2",
    ]
    for name, n, native in SPECS:
        assert 4 < n <= 8
        if role == "export":
            out.extend([
            "    .align 2",
            "    .global _" + name,
            "_" + name + ":",
            "    sts.l pr,@-r15",  # SP=S-4
            "    add #-16,r15",   # SP=S-20; native overflow is SP+0
            "    mov r15,r1",
            "    add #36,r1",     # incoming MS fifth: S+16 = current+36
        ])
        if role == "export":
            for i in range(n-4):
                out.extend(["    mov.l @r1+,r0",
                        ("    mov.l r0,@r15" if i == 0
                         else f"    mov.l r0,@({i*4},r15)")])
        if role == "export":
            out.extend([
            f"    mov.l .Lnative_{n},r0",
            "    jsr @r0",
            "    nop",
            "    add #16,r15",
            "    lds.l @r15+,pr",
            "    rts",
            "    nop",
            "    .align 2",
            f".Lnative_{n}: .long _{native}",
        ])

        # GCC caller enters with overflow words at S+0. Push GBR and PR
        # (8 bytes), allocate MSVC's full 32-byte home/overflow frame.
        # The MSVC callee can overwrite home slots; do not store state there.
        if role == "import":
            out.extend([
            "    .align 2",
            "    .global _ntos_msvc_import" + str(n),
            "_ntos_msvc_import" + str(n) + ":",
            "    stc.l gbr,@-r15",
            "    sts.l pr,@-r15",
            "    add #-32,r15",
            "    mov r15,r1",
            "    add #40,r1",     # GCC fifth S+0 = current+40
        ])
        if role == "import":
            for i in range(n-4):
                out.extend([
                "    mov.l @r1+,r0",
                f"    mov.l r0,@({16+i*4},r15)",
            ])
        if role == "import":
            out.extend([
            f"    mov.l .Liat_{n},r0",
            "    mov.l @r0,r0",
            "    jsr @r0",
            "    nop",
            "    add #32,r15",
            "    lds.l @r15+,pr",
            "    ldc.l @r15+,gbr",
            "    rts",
            "    nop",
            "    .align 2",
            f".Liat_{n}: .long ___imp_{name}",
        ])
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--role", choices=("import", "export"), required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(args.role), encoding="ascii")


if __name__ == "__main__":
    main()
