#!/usr/bin/env python3
"""Stage the existing NTOS SH4BE PE outputs in an EX-word SYSROOT.

The source is the existing make ntx/make all dist tree, not a second
compiler or checked-in binary. D01 size does not include these files.
"""
from __future__ import annotations

import argparse
from pathlib import Path, PurePosixPath
import shutil
import struct

REQUIRED = {"HELLO.EXE", "HELLOCORE.EXE", "COREDLL.DLL", "XAMLUI.DLL"}
ASSETS = {
    "home.dat", "apps.dat", "nav.dat", "edge.uxaml", "edgelight.uxaml",
    "calc.uxaml", "files.uxaml", "cortana.uxaml", "article.md",
    "logo.svf", "demo.md", "cool.svf", "swap.html",
}
MANIFEST = "NTOSH-BUILD-MODULES.TXT"


def sh4_pe(path: Path) -> None:
    """Fail if a packaged binary is not an SH4BE WinCE PE."""
    with path.open("rb") as handle:
        header = handle.read(64)
        if len(header) < 64 or header[:2] != b"MZ":
            raise ValueError(f"{path}: missing PE DOS header")
        offset = struct.unpack_from("<I", header, 0x3C)[0]
        if offset > path.stat().st_size - 6:
            raise ValueError(f"{path}: invalid PE header offset")
        handle.seek(offset)
        if handle.read(4) != b"PE\0\0" or handle.read(2) != b"\xa8\x01":
            raise ValueError(f"{path}: not SH4BE machine 0x01A8")


def products(dist: Path) -> dict[PurePosixPath, Path]:
    dist = dist.resolve()
    if not dist.is_dir():
        raise FileNotFoundError(f"missing compiled NTOS dist: {dist}")
    result: dict[PurePosixPath, Path] = {}

    def add(dest: PurePosixPath, src: Path, pe: bool = False) -> None:
        if src.is_symlink() or not src.is_file():
            raise ValueError(f"unsupported payload source: {src}")
        if pe:
            sh4_pe(src)
        if dest in result:
            raise ValueError(f"duplicate packaged path: {dest}")
        result[dest] = src

    root_pe = set()
    for path in sorted(dist.iterdir()):
        if not path.is_file():
            continue
        upper = path.name.upper()
        if path.suffix.upper() == ".EXE":
            add(PurePosixPath(upper), path, True)
            root_pe.add(upper)
        elif path.suffix.upper() in {".DLL", ".CPL"}:
            add(PurePosixPath("Windows", "System32", upper), path, True)
            root_pe.add(upper)
        elif path.name.lower() in ASSETS:
            add(PurePosixPath(path.name), path)

    missing = REQUIRED - root_pe
    if missing:
        raise FileNotFoundError(f"NTOS PE build incomplete: {sorted(missing)}")

    # Keep the NTOS.hh3 Apps directory structure, including case of names.
    apps = dist / "Apps"
    if apps.is_dir():
        for path in sorted(apps.rglob("*")):
            if path.is_file() and path.suffix.upper() == ".EXE":
                add(PurePosixPath("Apps", *path.relative_to(apps).parts), path, True)

    # The applet also has a standard WinCE Windows/demo.cpl alias.
    win = dist / "Windows"
    if win.is_dir():
        for path in sorted(win.glob("*.cpl")):
            add(PurePosixPath("Windows", path.name), path, True)
    return result


def package(dist: Path, folder: Path) -> int:
    mapping = products(dist)
    root = (folder / "SYSROOT").resolve()
    root.mkdir(parents=True, exist_ok=True)
    manifest = root / MANIFEST

    # Remove only files generated by a preceding build; retain hand-added
    # files and README text in a reused local install package.
    if manifest.exists():
        for line in manifest.read_text(encoding="utf-8").splitlines():
            relative = PurePosixPath(line)
            if not line or relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"unsafe previous manifest entry: {line!r}")
            old = root.joinpath(*relative.parts)
            if old.is_file() and old.resolve().is_relative_to(root):
                old.unlink()

    for relative, source in sorted(mapping.items(), key=lambda item: str(item[0])):
        destination = root.joinpath(*relative.parts)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)

    manifest.write_text(
        "".join(f"{path}\n" for path in sorted(mapping, key=str)),
        encoding="utf-8",
    )
    print(f"NTOSH {folder}: staged {len(mapping)} compiled SH4BE PE/assets")
    return len(mapping)


def check(dist: Path, folder: Path) -> None:
    mapping = products(dist)
    root = folder / "SYSROOT"
    manifest = root / MANIFEST
    assert manifest.is_file(), f"missing build manifest: {manifest}"
    actual = set(manifest.read_text(encoding="utf-8").splitlines())
    expected = {str(path) for path in mapping}
    assert actual == expected, (
        f"{folder}: missing={sorted(expected - actual)} "
        f"unexpected={sorted(actual - expected)}"
    )
    for relative, original in mapping.items():
        deployed = root.joinpath(*relative.parts)
        assert deployed.is_file(), f"missing {deployed}"
        assert deployed.read_bytes() == original.read_bytes(), f"stale {deployed}"
    assert not any(root.glob("*.DLL")), "DLL leaked outside System32"
    assert (root / "Windows" / "System32" / "COREDLL.DLL").is_file()
    print(f"PASS {folder}: {len(mapping)} current compiled NTOS payloads")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--from-dist", type=Path, required=True)
    parser.add_argument("--package", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check(args.from_dist, args.package)
    else:
        package(args.from_dist, args.package)
